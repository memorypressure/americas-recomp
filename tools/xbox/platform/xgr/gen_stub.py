"""Generate a logging stand-in xgameruntime.dll from the interface table made by idl_table.py.

usage: python -I gen_stub.py table.json out_dir          then: cl /nologo /LD /O2 /EHsc /std:c++17 out_dir\\xgr_stub.cpp /Fe:xgameruntime.dll /link /DEF:out_dir\\xgameruntime.def

The DLL exports the six entry points the GDK static library resolves (QueryApiImpl, InitializeApiImpl, InitializeApiImplEx, InitializeApiImplEx2,
UninitializeApiImpl, XErrorReport), plus XSystemGetDeviceType and XSystemGetRuntimeInfo: documented plain functions no interface of the IDL maps,
answered directly (in this generated stub; the runtime build answers them in runtime/impl_system.cpp). QueryApiImpl hands out one object per known interface id; every method of it logs its first call and returns a
failure (E_NOTIMPL for HRESULT methods, 0 for the rest, the hidden pointer for struct returns). Environment: XGR_LOG=<file>.
It exists to learn which runtime interfaces and methods a game uses, in which order, before any of them are implemented:
an interface id missing from the table is logged and refused (E_NOINTERFACE), which shows where the console build differs from the PC one.
"""
import json, os, sys

PLAIN_EXPORTS = ["XSystemGetDeviceType", "XSystemGetRuntimeInfo"]

SCALAR = {"void", "BOOLEAN", "bool", "INT32", "UINT32", "UINT64", "INT64", "SIZE_T", "size_t", "int", "UINT8", "UINT16", "float", "double"}


def guid_init(u):
    a = u.replace("-", "")
    d = [a[16 + 2 * i:18 + 2 * i] for i in range(8)]
    return "{0x%s, 0x%s, 0x%s, {%s}}" % (a[0:8], a[8:12], a[12:16], ", ".join("0x" + x for x in d))


def main():
    t = json.load(open(sys.argv[1]))["interfaces"]
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    by = {i["name"]: i for i in t}
    slots = []      # global slot -> (iface name, method name, kind)
    first = {}
    for i in t:
        names = {}
        chain = i
        while chain:
            for m in chain["methods"]:
                names.setdefault(m["slot"], m)
            chain = by.get(chain["parent"])
        first[i["name"]] = len(slots)
        for s in range(i["nslots"]):
            if s < 3:
                slots.append((i["name"], ["QueryInterface", "AddRef", "Release"][s], "unk"))
            else:
                m = names.get(s)
                if m:
                    r = m["ret"].replace("STDMETHODCALLTYPE", "").strip()
                    kind = "hr" if r == "HRESULT" else "zero" if r in SCALAR else "ptr"
                    slots.append((i["name"], m["name"], kind))
                else:
                    slots.append((i["name"], "slot%d" % s, "hr"))
    L = []
    L.append("// generated by gen_stub.py from the interface table; see that file. Do not edit.")
    L.append("#include <windows.h>\n#include <cstdio>\n#include <cstdint>\n#include <cstring>\n#include <mutex>\n#include <array>\n#include <utility>\n#pragma comment(lib, \"user32.lib\")")
    L.append("struct Slot { const char* iface; const char* name; int kind; };   // kind: 0 unk, 1 hr, 2 zero, 3 struct-return")
    L.append("static const Slot kSlots[] = {")
    for (i, n, k) in slots:
        L.append('  {"%s", "%s", %d},' % (i, n, {"unk": 0, "hr": 1, "zero": 2, "ptr": 3}[k]))
    L.append("};")
    L.append("struct Iface { const char* name; GUID iid; int first; int count; };")
    L.append("static const Iface kIfaces[] = {")
    for i in t:
        L.append('  {"%s", %s, %d, %d},' % (i["name"], guid_init(i["uuid"]), first[i["name"]], i["nslots"]))
    L.append("};")
    L.append(r'''
static FILE* g_log; static std::once_flag g_once; static bool g_seen[sizeof(kSlots) / sizeof(kSlots[0])];
static void Log(const char* fmt, ...) {
  std::call_once(g_once, [] { char p[MAX_PATH]; if (GetEnvironmentVariableA("XGR_LOG", p, MAX_PATH)) fopen_s(&g_log, p, "a"); });
  if (!g_log) return;
  va_list ap; va_start(ap, fmt); vfprintf(g_log, fmt, ap); va_end(ap); fputc('\n', g_log); fflush(g_log);
}
static void Fmt(const GUID& g, char* b) { sprintf_s(b, 40, "%08lx-%04x-%04x-%02x%02x-%02x%02x%02x%02x%02x%02x", g.Data1, g.Data2, g.Data3, g.Data4[0], g.Data4[1], g.Data4[2], g.Data4[3], g.Data4[4], g.Data4[5], g.Data4[6], g.Data4[7]); }

static uintptr_t OnCall(size_t gs, void* self, uintptr_t a1, uintptr_t a2, uintptr_t a3, void* ret) {
  const Slot& s = kSlots[gs];
  switch (s.kind) { case 0: return gs == 0 ? (uintptr_t)(uint32_t)E_NOINTERFACE : 1; }
  if (!g_seen[gs]) { g_seen[gs] = true; Log("call %s::%s args=%p %p %p ret=%p", s.iface, s.name, (void*)a1, (void*)a2, (void*)a3, ret); }
  if (s.kind == 1) return (uintptr_t)(uint32_t)E_NOTIMPL;
  if (s.kind == 3) return a1;
  return 0;
}
typedef uintptr_t (*StubFn)(void*, uintptr_t, uintptr_t, uintptr_t);
template <size_t N> uintptr_t Stub(void* self, uintptr_t a, uintptr_t b, uintptr_t c) { return OnCall(N, self, a, b, c, _ReturnAddress()); }
template <size_t... N> constexpr std::array<StubFn, sizeof...(N)> Make(std::index_sequence<N...>) { return {&Stub<N>...}; }
static constexpr auto kStubs = Make(std::make_index_sequence<sizeof(kSlots) / sizeof(kSlots[0])>{});

// XGR_WITH_RUNTIME: real implementations (runtime/ directory) replace the logging stub of every slot whose method name they provide.
#ifdef XGR_WITH_RUNTIME
namespace gtx::xgr { struct Override { const char* api; void* fn; }; const Override* overrides(size_t* count); }
static void* Override(int gs) {
  static std::once_flag once; static void* table[sizeof(kSlots) / sizeof(kSlots[0])];
  std::call_once(once, [] {
    size_t n = 0; const gtx::xgr::Override* ov = gtx::xgr::overrides(&n);
    for (size_t k = 0; k < sizeof(kSlots) / sizeof(kSlots[0]); k++)
      for (size_t j = 0; j < n; j++) if (!strcmp(kSlots[k].name, ov[j].api)) { table[k] = ov[j].fn; break; }
  });
  return table[gs] ? table[gs] : (void*)kStubs[gs];
}
#else
static void* Override(int gs) { return (void*)kStubs[gs]; }
#endif
struct Obj { void** vtbl; };
static Obj g_obj[sizeof(kIfaces) / sizeof(kIfaces[0])];
static void* g_vt[sizeof(kSlots) / sizeof(kSlots[0])];

extern "C" HRESULT QueryApiImpl(const GUID& provider, const GUID& iid, void** out) {
  if (!out) return E_POINTER;
  *out = nullptr;
  for (size_t i = 0; i < sizeof(kIfaces) / sizeof(kIfaces[0]); i++)
    if (IsEqualGUID(kIfaces[i].iid, iid)) {
      for (int s = 0; s < kIfaces[i].count; s++) g_vt[kIfaces[i].first + s] = Override(kIfaces[i].first + s);
      g_obj[i].vtbl = &g_vt[kIfaces[i].first];
      *out = &g_obj[i];
      Log("QueryApiImpl %s", kIfaces[i].name);
      return S_OK;
    }
  char a[40], b[40]; Fmt(provider, a); Fmt(iid, b);
  Log("QueryApiImpl UNKNOWN iid {%s} provider {%s}", b, a);
  return E_NOINTERFACE;
}
extern "C" HRESULT InitializeApiImpl(uint64_t a, uint64_t b) { Log("InitializeApiImpl %llx %llx", a, b); return S_OK; }
extern "C" HRESULT InitializeApiImplEx(uint64_t a, uint64_t b, uint64_t f) { Log("InitializeApiImplEx %llx %llx flags=%llx", a, b, f); return S_OK; }
extern "C" HRESULT InitializeApiImplEx2(uint64_t a, uint64_t b, uint64_t f, void* o) { Log("InitializeApiImplEx2 %llx %llx flags=%llx options=%p", a, b, f, o); return S_OK; }
#ifdef XGR_WITH_RUNTIME
namespace gtx::xgr::system { void report_error(HRESULT hr, const char* message); }
namespace gtx::xgr::handles { void report_leaks(); }
#endif
extern "C" void UninitializeApiImpl() {
  Log("UninitializeApiImpl");
#ifdef XGR_WITH_RUNTIME
  gtx::xgr::handles::report_leaks();
#endif
}
extern "C" void XErrorReport(HRESULT hr, const char* m) {
  Log("XErrorReport %08lx %s", (unsigned long)hr, m ? m : "");
#ifdef XGR_WITH_RUNTIME
  gtx::xgr::system::report_error(hr, m);
#endif
}

// Direct exports the interface table does not map (no interface slot is known for either). With the
// runtime linked, runtime/impl_system.cpp defines them; the logging stub answers the same documented
// values here so the export table is complete in either build (see the .def).
#ifndef XGR_WITH_RUNTIME
extern "C" uint32_t XSystemGetDeviceType(void) { Log("XSystemGetDeviceType"); return 1; }   // XSystemDeviceType::Pc
struct StubRuntimeInfo { uint16_t runtimeVersion[4], availableVersion[4]; };                 // XSystemRuntimeInfo
extern "C" StubRuntimeInfo XSystemGetRuntimeInfo(void) { Log("XSystemGetRuntimeInfo"); StubRuntimeInfo z{}; return z; }
#endif
''')
    open(os.path.join(out, "xgr_stub.cpp"), "w").write("\n".join(L).replace("#include <utility>", "#include <utility>\n#include <cstdarg>\n#include <intrin.h>"))
    open(os.path.join(out, "xgameruntime.def"), "w").write("LIBRARY xgameruntime\nEXPORTS\n    QueryApiImpl\n    InitializeApiImpl\n    InitializeApiImplEx\n    InitializeApiImplEx2\n    UninitializeApiImpl\n    XErrorReport\n" + "".join("    %s\n" % n for n in PLAIN_EXPORTS))
    print("%d interfaces, %d vtable slots -> %s" % (len(t), len(slots), out))


main()
